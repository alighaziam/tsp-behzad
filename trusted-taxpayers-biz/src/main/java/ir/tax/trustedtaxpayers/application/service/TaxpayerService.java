package ir.tax.trustedtaxpayers.application.service;

import ir.tax.trustedtaxpayers.application.cache.CacheEvict;
import ir.tax.trustedtaxpayers.application.cache.Cacheable;
import ir.tax.trustedtaxpayers.application.cache.NoCache;
import ir.tax.trustedtaxpayers.core.spec.BaseSpecification;
import ir.tax.trustedtaxpayers.core.spec.FilterRequest;
import ir.tax.trustedtaxpayers.infrastructure.jpa.entity.TaxpayerEntity;
import ir.tax.trustedtaxpayers.infrastructure.jpa.repository.TaxpayerRepository;
import ir.tax.trustedtaxpayers.infrastructure.jpa.spec.FilterOperand;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.stream.Collectors;

@Service
public class TaxpayerService extends ir.tax.trustedtaxpayers.core.service.BaseCacheServiceImpl<TaxpayerEntity, UUID> {
    
    private final TaxpayerRepository taxpayerRepository;

    public TaxpayerService(TaxpayerRepository taxpayerRepository) {
        super(taxpayerRepository);
        this.taxpayerRepository = taxpayerRepository;
    }

    @CacheEvict(cacheName = "taxpayers", allEntries = true)
    @Transactional
    public UUID create(TaxpayerEntity taxpayer) {
        // ID will be auto-generated by BaseEntity.ensureId()
        taxpayer.setIsActive(true);
        UUID taxpayerId = save(taxpayer).getId();
        
        // Login accounts and taxpayer access mappings are provisioned separately
        // by an administrator; never create accounts with a predictable default password.
        
        return taxpayerId;
    }

    @CacheEvict(cacheName = "taxpayers", allEntries = true)
    @Override
    @Transactional
    public TaxpayerEntity update(UUID id, TaxpayerEntity updatedTaxpayer) {
        TaxpayerEntity existing = findById(id).orElseThrow();
        if (updatedTaxpayer.getTaxId() != null) {
            existing.setTaxId(updatedTaxpayer.getTaxId());
        }
        if (updatedTaxpayer.getName() != null) {
            existing.setName(updatedTaxpayer.getName());
        }
        return save(existing);
    }

    @NoCache  // Optional cannot be properly serialized/deserialized from cache
    @Transactional(readOnly = true)
    public Optional<TaxpayerEntity> findByTaxId(String taxId) {
        return taxpayerRepository.findByTaxId(taxId);
    }

    @Transactional(readOnly = true)
    public List<TaxpayerEntity> findByName(String name) {
        if (name == null || name.isBlank()) {
            return taxpayerRepository.findAll();
        }
        return taxpayerRepository.findByNameContainingIgnoreCase(name);
    }

    @Cacheable(cacheName = "taxpayers", keyPrefix = "exists")
    @Transactional(readOnly = true)
    public boolean existsByTaxId(String taxId) {
        return taxpayerRepository.findByTaxId(taxId).isPresent();
    }

    @NoCache  // Optional cannot be properly serialized/deserialized from cache
    @Transactional(readOnly = true)
    public Optional<TaxpayerEntity> findByNationalId(String nationalId) {
        return taxpayerRepository.findByNationalId(nationalId);
    }

    @Transactional(readOnly = true)
    public List<TaxpayerEntity> search(String query) {
        return search(query, 30, 0);
    }

    @Transactional(readOnly = true)
    public List<TaxpayerEntity> search(String query, int limit) {
        return search(query, limit, 0);
    }

    @Transactional(readOnly = true)
    public List<TaxpayerEntity> search(String query, int limit, int page) {
        int safeLimit = Math.min(Math.max(limit, 1), 100);
        int safePage = Math.max(page, 0);
        Pageable pageable = PageRequest.of(safePage, safeLimit, Sort.by(Sort.Direction.ASC, "name"));

        if (query == null || query.isBlank()) {
            return taxpayerRepository.findAll(pageable).getContent();
        }
        return taxpayerRepository
                .findByTaxIdContainingIgnoreCaseOrNameContainingIgnoreCase(query, query, pageable)
                .getContent();
    }

    @Transactional(readOnly = true)
    public List<TaxpayerEntity> findBy(String key, String operand, Object value) {
        if (key == null || key.isBlank() || operand == null || operand.isBlank()) {
            return taxpayerRepository.findAll();
        }
        FilterRequest filterRequest = new FilterRequest();
        filterRequest.setKey(key);
        try {
            FilterOperand op = FilterOperand.valueOf(operand.toLowerCase());
            filterRequest.setOperand(convertOperandToString(op));
        } catch (IllegalArgumentException e) {
            filterRequest.setOperand("=");
        }
        filterRequest.setValue(value);
        Specification<TaxpayerEntity> spec = new BaseSpecification<>(List.of(filterRequest));
        return taxpayerRepository.findAll(spec);
    }

    @CacheEvict(cacheName = "taxpayers", allEntries = true)
    @Override
    @Transactional
    public void deleteById(UUID id) {
        super.deleteById(id);
    }

    @Transactional(readOnly = true)
    public Page<TaxpayerEntity> search(List<ir.tax.trustedtaxpayers.application.dto.SearchRequest.Filter> filters,
                                       Integer page, Integer size, String sortBy, String direction) {
        List<FilterRequest> filterRequests = new ArrayList<>();
        if (filters != null) {
            filterRequests = filters.stream()
                    .map(f -> {
                        FilterRequest filterRequest = new FilterRequest();
                        filterRequest.setKey(f.getKey());
                        filterRequest.setOperand(f.getOperand());
                        filterRequest.setValue(f.getValue());
                        return filterRequest;
                    })
                    .collect(Collectors.toList());
        }
        
        BaseSpecification<TaxpayerEntity> spec = new BaseSpecification<>(filterRequests);

        org.springframework.data.domain.Sort.Direction sortDirection = 
            org.springframework.data.domain.Sort.Direction.ASC;
        if (direction != null && direction.trim().equalsIgnoreCase("desc")) {
            sortDirection = org.springframework.data.domain.Sort.Direction.DESC;
        }
        
        String validSortBy = sortBy != null && !sortBy.isBlank() ? sortBy : "id";
        org.springframework.data.domain.Sort sort = 
            org.springframework.data.domain.Sort.by(sortDirection, validSortBy);

        int validPage = page != null && page >= 0 ? page : 0;
        int validSize = size != null && size > 0 ? Math.min(size, 100) : 10;
        
        org.springframework.data.domain.Pageable pageable = 
            org.springframework.data.domain.PageRequest.of(validPage, validSize, sort);

        return taxpayerRepository.findAll(spec, pageable);
    }
    
    private String convertOperandToString(FilterOperand operand) {
        return switch (operand) {
            case equal -> "=";
            case like -> "like";
            case gt -> ">";
            case lt -> "<";
            case gte -> ">=";
            case lte -> "<=";
            case in -> "=";
        };
    }
}


