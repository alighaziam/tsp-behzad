package ir.tax.trustedtaxpayers.application.service;

import ir.tax.trustedtaxpayers.core.service.BaseServiceImpl;
import ir.tax.trustedtaxpayers.infrastructure.jpa.entity.AuditLogEntity;
import ir.tax.trustedtaxpayers.infrastructure.jpa.repository.AuditLogRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.UUID;

@Service
public class AuditLogService extends BaseServiceImpl<AuditLogEntity, UUID> {
    private final AuditLogRepository auditLogRepository;

    public AuditLogService(AuditLogRepository auditLogRepository) {
        super(auditLogRepository);
        this.auditLogRepository = auditLogRepository;
    }

    @Transactional
    public UUID create(AuditLogEntity auditLog) {
        // ID will be auto-generated by BaseEntity.ensureId()
        if (auditLog.getCreatedOn() == null) {
            auditLog.setCreatedOn(OffsetDateTime.now());
        }
        return save(auditLog).getId();
    }

    @Override
    @Transactional
    public AuditLogEntity update(UUID id, AuditLogEntity updatedAuditLog) {
        AuditLogEntity existing = findById(id).orElseThrow();
        if (updatedAuditLog.getCreatedOn() != null) {
            existing.setCreatedOn(updatedAuditLog.getCreatedOn());
        }
        if (updatedAuditLog.getActorUserId() != null) {
            existing.setActorUserId(updatedAuditLog.getActorUserId());
        }
        if (updatedAuditLog.getEntityName() != null) {
            existing.setEntityName(updatedAuditLog.getEntityName());
        }
        if (updatedAuditLog.getEntityId() != null) {
            existing.setEntityId(updatedAuditLog.getEntityId());
        }
        if (updatedAuditLog.getAction() != null) {
            existing.setAction(updatedAuditLog.getAction());
        }
        if (updatedAuditLog.getDetails() != null) {
            existing.setDetails(updatedAuditLog.getDetails());
        }
        return save(existing);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> getAll() {
        return findAll();
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> findByActorUserId(UUID actorUserId) {
        return auditLogRepository.findByActorUserId(actorUserId);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> findByEntityName(String entityName) {
        return auditLogRepository.findByEntityName(entityName);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> findByAction(String action) {
        return auditLogRepository.findByAction(action);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> findByEntityNameAndEntityId(String entityName, String entityId) {
        return auditLogRepository.findByEntityNameAndEntityId(entityName, entityId);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> findByEventTimeBetween(OffsetDateTime start, OffsetDateTime end) {
        return auditLogRepository.findByEventTimeBetween(start, end);
    }

    public boolean existsById(UUID id) {
        return exists(id);
    }

    @Transactional(readOnly = true)
    public List<AuditLogEntity> search(String query) {
        if (query == null || query.isBlank()) {
            return auditLogRepository.findAll();
        }
        return auditLogRepository.searchIgnoreCase(query);
    }
}


