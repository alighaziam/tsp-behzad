CREATE TABLE ELECTRONIC_INVOICE_SYSTEM
(
    HEADER_ID        RAW(16) NOT NULL,
    IS_ACTIVE        NUMBER(1),
    CREATED_ON       TIMESTAMP WITH TIME ZONE,
    UPDATED_ON       TIMESTAMP WITH TIME ZONE,
    CREATED_BY       VARCHAR2(100),
    UPDATED_BY       VARCHAR2(100),
    SIGN             VARCHAR2(250),
    CERT             VARCHAR2(250),
    HASH             VARCHAR2(128),
    STS              VARCHAR2(20),
    REFERENCE_NUMBER VARCHAR2(50),
    SRVDT            TIMESTAMP WITH TIME ZONE,
    REJCODE          VARCHAR2(20),
    REJDESC          VARCHAR2(400),
    CONSTRAINT PK_ELECTRONIC_INVOICE_SYSTEM PRIMARY KEY (HEADER_ID),
    CONSTRAINT FK_ELECTRONIC_INVOICE_SYSTEM_HEADER FOREIGN KEY (HEADER_ID)
        REFERENCES ELECTRONIC_INVOICE_HEADER (ID)
);
