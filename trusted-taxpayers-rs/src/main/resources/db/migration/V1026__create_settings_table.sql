CREATE TABLE SETTINGS (
  ID RAW(16) NOT NULL,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
  UPDATED_ON TIMESTAMP WITH TIME ZONE,
  CREATED_BY VARCHAR2(100),
  UPDATED_BY VARCHAR2(100),
  PATH VARCHAR2(500 CHAR),
  URL VARCHAR2(1000 CHAR),
  KEY_NAME VARCHAR2(100 CHAR) NOT NULL,
  "VALUE" VARCHAR2(4000 CHAR),
  PASS VARCHAR2(500 CHAR),
  GROUP_TYPE VARCHAR2(50 CHAR)
);

ALTER TABLE SETTINGS ADD CONSTRAINT PK_SETTINGS PRIMARY KEY (ID);

ALTER TABLE SETTINGS ADD CONSTRAINT UK_SETTINGS_KEY_NAME UNIQUE (KEY_NAME);
