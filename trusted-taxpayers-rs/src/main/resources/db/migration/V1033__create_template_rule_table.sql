CREATE TABLE TEMPLATE_RULE (
  ID RAW(16) NOT NULL,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
  UPDATED_ON TIMESTAMP WITH TIME ZONE,
  CREATED_BY VARCHAR2(100),
  UPDATED_BY VARCHAR2(100),
  TEMPLATE_CODE VARCHAR2(10 CHAR) NOT NULL,
  FIELD_NAME VARCHAR2(100 CHAR) NOT NULL,
  RULE_TYPE VARCHAR2(30 CHAR) NOT NULL,
  RULE_PARAMS VARCHAR2(4000 CHAR),
  EXPLANATION VARCHAR2(4000 CHAR),
  ACTIVE VARCHAR2(1 CHAR) DEFAULT '1' NOT NULL
);

ALTER TABLE TEMPLATE_RULE ADD CONSTRAINT PK_TEMPLATE_RULE PRIMARY KEY (ID);

