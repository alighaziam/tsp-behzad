  DESCRIPTION VARCHAR2(1000 CHAR),
  PRICE NUMBER(18,2) NOT NULL,
  CURRENCY VARCHAR2(10 CHAR) NOT NULL,
  DURATION_DAYS NUMBER(10) NOT NULL,
  MAX_INVOICES NUMBER(10),
