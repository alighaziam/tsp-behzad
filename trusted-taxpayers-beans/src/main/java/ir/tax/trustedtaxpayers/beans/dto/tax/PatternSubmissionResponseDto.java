package ir.tax.trustedtaxpayers.beans.dto.tax;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.OffsetDateTime;
import java.util.UUID;

/**
 * پاسخ ارسال درخواست الگو شامل وضعیت نهایی، نتایج اعتبارسنجی و شناسه‌ها.
 * <p>
 * Submission response describing final transmission status, validation outcome, and identifiers.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class PatternSubmissionResponseDto {

    /**
     * شناسه درخواست مرتبط.
     * <p>
     * Identifier of the associated request.
     */
    @Schema(description = "شناسه درخواست")
    private UUID requestId;

    /**
     * شناسه سربرگ ذخیره‌شده در سامانه بیرونی.
     * <p>
     * Header identifier generated by downstream systems.
     */
    @Schema(description = "شناسه سربرگ صورتحساب ثبت‌شده")
    private UUID headerId;

    /**
     * شناسه مالیاتی اختصاص‌یافته.
     * <p>
     * Generated tax identifier.
     */
    @Schema(description = "شناسه مالیاتی تولیدشده")
    private String taxId;

    /**
     * وضعیت ارسال گزارش‌شده توسط سامانه مقصد.
     * <p>
     * Transmission status returned by the external system.
     */
    @Schema(description = "وضعیت ارسال به سامانه")
    private String transmissionStatus;

    /**
     * پیام تکمیلی وضعیت (در صورت وجود).
     * <p>
     * Optional status message.
     */
    @Schema(description = "پیام تکمیلی وضعیت")
    private String message;

    /**
     * شناسه یا نام درخواست‌کننده.
     * <p>
     * Identifier or name of the requester.
     */
    @Schema(description = "شناسه یا نام third-party درخواست کننده")
    private String requestedBy;

    /**
     * کلید یونیک third-party.
     * <p>
     * Unique client key.
     */
    @Schema(description = "کلید یونیک third-party")
    private String clientKey;

    /**
     * نام شرکت طرف قرارداد.
     * <p>
     * Display name of the client.
     */
    @Schema(description = "نام third-party")
    private String clientName;

    /**
     * شناسه اختصاصی قابل‌ارائه به third-party.
     * <p>
     * External request id exposed to the third-party.
     */
    @Schema(description = "شناسه یونیک اختصاص داده شده برای third-party")
    private String externalRequestId;

    /**
     * وضعیت معوق بودن ارسال.
     * <p>
     * Indicates whether the submission is deferred.
     */
    @Schema(description = "آیا ارسال به صورت معوق است؟", example = "false")
    private boolean deferredSubmission;

    /**
     * تایید یا عدم تایید ارسال معوق.
     * <p>
     * Indicates whether deferred submission has been approved.
     */
    @Schema(description = "آیا درخواست معوق تایید شده است؟", example = "false")
    private boolean deferredApproved;

    /**
     * کد رد در صورت وقوع.
     * <p>
     * Rejection code when applicable.
     */
    @Schema(description = "کد رد در صورت وجود")
    private String rejectionCode;

    /**
     * شرح خطای رد شده.
     * <p>
     * Rejection description providing details.
     */
    @Schema(description = "شرح رد در صورت وجود")
    private String rejectionDescription;

    /**
     * نتیجه کامل اعتبارسنجی انجام‌شده.
     * <p>
     * Validation result payload.
     */
    @Schema(description = "نتیجه اعتبارسنجی")
    private ValidationResultDto validation;

    /**
     * موفقیت نهایی عملیات.
     * <p>
     * Indicates overall success flag.
     */
    @Schema(description = "موفقیت نهایی عملیات")
    private boolean success;

    /**
     * زمان تکمیل چرخه درخواست.
     * <p>
     * Timestamp when the request completed.
     */
    @Schema(description = "زمان تکمیل درخواست")
    private OffsetDateTime completedAt;
}
