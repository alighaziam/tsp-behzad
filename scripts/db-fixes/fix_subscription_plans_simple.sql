-- Add foreign key constraints if they don't exist
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE TAXPAYER_SUBSCRIPTIONS ADD CONSTRAINT FK_TS_TAXPAYER FOREIGN KEY (TAXPAYER_ID) REFERENCES TAXPAYER(ID)';
  DBMS_OUTPUT.PUT_LINE('FK_TS_TAXPAYER constraint added.');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -2275 OR SQLCODE = -942 THEN
      DBMS_OUTPUT.PUT_LINE('FK_TS_TAXPAYER constraint already exists or TAXPAYER table missing.');
    ELSE
      DBMS_OUTPUT.PUT_LINE('Error adding FK_TS_TAXPAYER: ' || SQLERRM);
    END IF;
END;
/

